    total_expenses = state["metrics"].get("total_expenses", 0) + state["metrics"].get("total_campaign_spend", 0)
    margin = (total_revenue - total_expenses) / total_revenue if total_revenue else 0
    avg_client_value = state["mrr"] / max(1, len(active_clients(state)))
