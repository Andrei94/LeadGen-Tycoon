def svg_chart_panel(title, series):
    width = 720
    height = 260
    left = 58
    right = 18
    top = 18
    bottom = 38
    values = [float(value) for item in series for value in item["values"]]
    if not values:
        values = [0]
    minimum = min(0, min(values))
    maximum = max(values)
    if maximum == minimum:
        maximum += 1
    x_values = []
    max_points = max((len(item["values"]) for item in series), default=1)
    for index in range(max_points):
        x = left + (width - left - right) * (index / max(1, max_points - 1))
        x_values.append(x)

    grid_lines = []
    for index in range(5):
        ratio = index / 4
        y = top + (height - top - bottom) * ratio
        label_value = maximum - (maximum - minimum) * ratio
        label = money(label_value) if maximum >= 1000 else f"{label_value:,.0f}"
        grid_lines.append(
            f'<line x1="{left}" y1="{y:.1f}" x2="{width - right}" y2="{y:.1f}" stroke="#e8edf3" stroke-width="1" />'
            f'<text x="10" y="{y + 4:.1f}" fill="#657184" font-size="11">{escape(label)}</text>'
        )

    lines = []
    for item in series:
        points = []
        for index, value in enumerate(item["values"]):
            x = x_values[index]
            y = top + (height - top - bottom) * ((maximum - float(value)) / (maximum - minimum))
            points.append(f"{x:.1f},{y:.1f}")
        if len(points) == 1:
            points.append(f"{width - right:.1f},{points[0].split(',')[1]}")
        lines.append(
            f'<polyline points="{" ".join(points)}" fill="none" stroke="{item["color"]}" stroke-width="3" '
            f'stroke-linecap="round" stroke-linejoin="round" />'
        )

    legend = ""
    for index, item in enumerate(series):
        x = left + index * 150
        y = height - 12
        legend += (
            f'<circle cx="{x}" cy="{y - 4}" r="4" fill="{item["color"]}" />'
            f'<text x="{x + 10}" y="{y}" fill="#657184" font-size="12">{escape(item["label"])}</text>'
        )

    html = f"""
    <div class="lg-chart-card">
      <h3>{escape(title)}</h3>
      <svg viewBox="0 0 {width} {height}" role="img" aria-label="{escape(title)} chart">
        <rect x="0" y="0" width="{width}" height="{height}" fill="#ffffff" />
        {"".join(grid_lines)}
        {"".join(lines)}
        {legend}
      </svg>
    </div>
    """
    st.markdown(html, unsafe_allow_html=True)


