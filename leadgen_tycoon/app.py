def money(value: float) -> str:
    sign = "-" if value < 0 else ""
    return f"{sign}${abs(value):,.0f}"


def percent(value: float) -> str:
    return f"{value:.1%}"


def tooltip_badge(text: str) -> str:
    tip = escape(str(text), quote=True)
    return (
        f'<span class="lg-help" title="{tip}" data-tooltip="{tip}" aria-label="{tip}" tabindex="0">'
        f'?<span class="lg-tooltip-text" aria-hidden="true">{tip}</span></span>'
    )


def tooltip_line(label: str, text: str) -> str:
    return f'<span class="lg-subtle">{escape(label)} {tooltip_badge(text)}</span>'


def effect_summary(effects: dict) -> str:
    readable = []
    for key, value in effects.items():
        label = EFFECT_LABELS.get(key, key.replace("_", " "))
        if isinstance(value, (int, float)):
            if abs(value) < 1:
                readable.append(f"{label}: {value:+.0%}")
            else:
                readable.append(f"{label}: {value:+g}")
        else:
            readable.append(label)
    return "; ".join(readable) if readable else "This affects gameplay through its listed benefits and tradeoffs."


def queue_notification(message: str):
    st.session_state.setdefault("pending_notifications", []).append(message)


def flush_notifications():
    pending = st.session_state.get("pending_notifications", [])
    if not pending:
        return
    st.session_state.pending_notifications = []
    for message in pending:
        st.toast(message)


def get_lan_hint() -> str:
    try:
        host = socket.gethostbyname(socket.gethostname())
        if host and not host.startswith("127."):
            return f"http://{host}:8501"
    except OSError:
        pass
    return "http://YOUR-COMPUTER-IP:8501"


def default_actions():
    return {
        "campaigns": {
            "cold_email": {"enabled": True, "intensity": 1, "budget": 80},
            "linkedin_outreach": {"enabled": True, "intensity": 1, "budget": 40},
            "sales_calls": {"enabled": True, "intensity": 1, "budget": 0},
        },
        "training": {skill: 0 for skill in SKILLS},
    }


def init_session():
    if "game" not in st.session_state:
        saved = load_game()
        st.session_state.game = saved if saved else new_game()
    st.session_state.game = normalize_state(st.session_state.game)
    if "weekly_actions" not in st.session_state:
        st.session_state.weekly_actions = default_actions()
    if st.session_state.get("nav") not in NAV_ITEMS:
        st.session_state.nav = "Dashboard"
    if st.session_state.get("nav_radio") not in NAV_ITEMS:
        st.session_state.nav_radio = st.session_state.nav
    if "pending_notifications" not in st.session_state:
        st.session_state.pending_notifications = []


def persist():
    refresh_business_metrics(st.session_state.game)
    try:
        save_game(st.session_state.game)
        st.session_state.save_error = ""
    except OSError as exc:
        st.session_state.save_error = f"Save failed: {exc}"


def run_week():
    completed_week = st.session_state.game.get("week", 1)
    st.session_state.game = simulate_week(st.session_state.game, st.session_state.weekly_actions)
    unlocked = st.session_state.game.get("last_achievements", [])
    persist()
    queue_notification(f"Week {completed_week} simulated and saved.")
    for achievement in unlocked:
        queue_notification(
            f"Achievement unlocked: {achievement['name']} - {achievement['description']} (+{achievement.get('xp', 0)} XP)"
        )


